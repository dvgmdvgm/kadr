export type TKey = keyof typeof ru

export function useT(): (k: TKey) => string {
  const lang = useSettings((s) => s.lang)
  return (k) => (lang === 'ru' ? ru : en)[k]
}

/** The same table outside React — for code that has no component to hook in. */
export function tr(k: TKey): string {
  return (useSettings.getState().lang === 'ru' ? ru : en)[k]
}

/** The label in a named language — the command palette searches both. */
/** tr() with {name} placeholders filled from args. */
export function trf(k: TKey, args: Record<string, string | number>): string {
  return tr(k).replace(/\{(\w+)\}/g, (m, n: string) => (n in args ? String(args[n]) : m))
}

/** A 'one|few|many' (ru) or 'one|other' (en) key, picked for n. */
export function trPlural(k: TKey, n: number): string {
  const forms = tr(k).split('|')
  if (forms.length < 3) return forms[n === 1 ? 0 : forms.length - 1]
  const m10 = n % 10, m100 = n % 100
  return forms[m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2]
}

export const trIn = (lang: 'ru' | 'en', k: TKey): string => (lang === 'ru' ? ru : en)[k]

/** A Said from main in the UI language; an arg that is a Said is said first. An unknown key reads as itself. */
export function say(s: Said): string {
  const args: Record<string, string | number> = {}
  for (const [k, v] of Object.entries(s.args ?? {})) args[k] = typeof v === 'object' ? say(v) : v
  return s.key in ru ? trf(s.key as TKey, args) : s.key
}

/** Text that may carry main's Said mark (a warning, an IPC error) in the UI language; plain text as it is. */
export function spoken(text: string): string {
  const s = parseSaid(text)
  return s ? say(s) : text
}

/** Every window.kadr call rejects with main's error in the UI language (electron/*: saidError). */
export function speakMainErrors(): void {
  const api = (globalThis as unknown as { kadr?: Record<string, unknown> }).kadr
  if (!api) return
  for (const [name, f] of Object.entries(api)) {
    if (typeof f !== 'function') continue
    api[name] = (...a: unknown[]) => {
      const r = f.apply(api, a)
      return r instanceof Promise ? r.catch((e: unknown) => {
        const s = e instanceof Error ? parseSaid(e.message) : null
        throw s ? new Error(say(s)) : e
      }) : r
    }
  }
}
